@contextlib.contextmanager
def _mocked_crypto(*fingerprints: str):
    """Isolate add_host()'s file/directory orchestration from real age-keygen/sops.

    generate_age_key() is patched to return *fingerprints* in call order
    (each add_host() call inside the `with` block consumes the next one);
    _create_host_secrets_file() (the only sops-shelling step) is a no-op.
    Real sops/age integration is TestAddHostSops's job, not this one's.
    """
    with (
        patch("mac2nix.generators.scaffold.generate_age_key", side_effect=list(fingerprints)),
        patch("mac2nix.generators.scaffold._create_host_secrets_file"),
    ):
        yield


class TestAddHostFiles:
    def test_first_host_creates_files_with_placeholders_substituted(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        with _mocked_crypto("age1hosta-fingerprint"):
            fingerprint = add_host(output_dir, "hosta", "alice", confirm_backup=lambda _: True)

        assert fingerprint == "age1hosta-fingerprint"

        config = (output_dir / "hosts" / "darwin" / "hosta" / "configuration.nix").read_text()
        assert "__HOSTNAME__" not in config
        assert "__USERNAME__" not in config
        assert "hosta" in config
        assert "alice" in config

        meta = json.loads((output_dir / "hosts" / "darwin" / "hosta" / ".mac2nix-meta.json").read_text())
        assert meta == {
            "hostname": "hosta",
            "username": "alice",
            "system": "aarch64-darwin",
            "age_public_key": "age1hosta-fingerprint",
        }

        user_config = (output_dir / "users" / "alice.nix").read_text()
        assert "__USERNAME__" not in user_config
        assert "alice" in user_config

    def test_second_host_same_username_leaves_user_file_untouched(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        with _mocked_crypto("age1hosta-fingerprint", "age1hostb-fingerprint"):
            add_host(output_dir, "hosta", "shareduser", confirm_backup=lambda _: True)

            user_file = output_dir / "users" / "shareduser.nix"
            before_mtime = user_file.stat().st_mtime_ns
            before_content = user_file.read_text()

            add_host(output_dir, "hostb", "shareduser", confirm_backup=lambda _: True)

        assert user_file.stat().st_mtime_ns == before_mtime
        assert user_file.read_text() == before_content
        assert (output_dir / "hosts" / "darwin" / "hosta").is_dir()
        assert (output_dir / "hosts" / "darwin" / "hostb").is_dir()

    def test_duplicate_hostname_raises_and_writes_nothing(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        with _mocked_crypto("age1hosta-fingerprint"):
            add_host(output_dir, "hosta", "alice", confirm_backup=lambda _: True)

