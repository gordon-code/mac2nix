    def test_confirm_backup_false_leaves_no_host_artifacts(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        with _mocked_crypto("age1hosta-fingerprint"), pytest.raises(ScaffoldError, match="not confirmed"):
            add_host(output_dir, "hosta", "alice", confirm_backup=lambda _: False)

        assert not (output_dir / "hosts" / "darwin" / "hosta").exists()
        assert not (output_dir / "users" / "alice.nix").exists()
        assert not (output_dir / "secrets" / "hosta.yaml").exists()

        flake_content = (output_dir / "flake.nix").read_text()
