@pytest.mark.nix
@pytest.mark.usefixtures("require_add_host_crypto_deps")
class TestAddHostSops:
    def test_host_a_produces_correctly_scoped_sops_and_secrets(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        with _redirect_age_keys(tmp_path / "age-keys"):
            fingerprint_a = add_host(output_dir, "hosta", "alice", confirm_backup=lambda _: True)

        sops_config = yaml.safe_load((output_dir / ".sops.yaml").read_text())
        rules = sops_config["creation_rules"]
        assert len(rules) == 1
        assert rules[0]["key_groups"] == [{"age": [fingerprint_a]}]
        assert re.search(rules[0]["path_regex"], "secrets/hosta.yaml")
        assert not re.search(rules[0]["path_regex"], "secrets/hostb.yaml")

        assert (output_dir / "secrets" / "hosta.yaml").is_file()

    def test_host_b_added_without_disturbing_host_a_and_cannot_decrypt_its_secrets(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)
        key_root = tmp_path / "age-keys"

        with _redirect_age_keys(key_root):
            add_host(output_dir, "hosta", "alice", confirm_backup=lambda _: True)

            meta_a_path = output_dir / "hosts" / "darwin" / "hosta" / ".mac2nix-meta.json"
            secrets_a_path = output_dir / "secrets" / "hosta.yaml"
            meta_a_before = meta_a_path.read_text()
            secrets_a_before = secrets_a_path.read_text()

            add_host(output_dir, "hostb", "bob", confirm_backup=lambda _: True)

        # A's own files are untouched by B's registration.
        assert meta_a_path.read_text() == meta_a_before
        assert secrets_a_path.read_text() == secrets_a_before

        sops_config = yaml.safe_load((output_dir / ".sops.yaml").read_text())
        flake_content = (output_dir / "flake.nix").read_text()
        assert len(sops_config["creation_rules"]) == 2
        assert "hosta" in flake_content
        assert "hostb" in flake_content

        # B's key cannot decrypt A's secrets — a real sops --decrypt attempt.
        b_key_path = key_root / "bob" / "keys.txt"
        env = {**os.environ, "SOPS_AGE_KEY_FILE": str(b_key_path)}
        result = subprocess.run(  # noqa: S603
            ["sops", "--decrypt", str(secrets_a_path)],  # noqa: S607
            cwd=output_dir,
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )
        assert result.returncode != 0

    def test_duplicate_key_metadata_triggers_uniqueness_error_and_rolls_back(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)
        key_root = tmp_path / "age-keys"

        with _redirect_age_keys(key_root):
            fingerprint_a = add_host(output_dir, "hosta", "alice", confirm_backup=lambda _: True)

            with (
                patch("mac2nix.generators.scaffold.generate_age_key", return_value=fingerprint_a),
                pytest.raises(ScaffoldError, match="share the same age public key"),
            ):
                add_host(output_dir, "hostc", "carol", confirm_backup=lambda _: True)

        # Rollback: hostc leaves no trace, flake.nix/.sops.yaml revert to hosta only.
        assert not (output_dir / "hosts" / "darwin" / "hostc").exists()
        assert not (output_dir / "users" / "carol.nix").exists()
        assert not (output_dir / "secrets" / "hostc.yaml").exists()

        flake_content = (output_dir / "flake.nix").read_text()
        assert "hostc" not in flake_content
        assert "hosta" in flake_content

        sops_config = yaml.safe_load((output_dir / ".sops.yaml").read_text())
        rules = sops_config["creation_rules"]
        assert len(rules) == 1
        assert rules[0]["key_groups"] == [{"age": [fingerprint_a]}]
