class TestInitFramework:
    def test_produces_expected_framework_files(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        for rel_path in _EXPECTED_FRAMEWORK_FILES:
            assert (output_dir / rel_path).is_file(), f"missing {rel_path}"

    def test_gitignore_renamed_bare_gitignore_absent(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        assert (output_dir / ".gitignore").is_file()
        assert not (output_dir / "gitignore").exists()

    def test_flake_nix_has_empty_host_sentinels(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        lines = (output_dir / "flake.nix").read_text().splitlines()
        begin_line = next(i for i, line in enumerate(lines) if "MAC2NIX:HOSTS:BEGIN" in line)
        end_line = next(i for i, line in enumerate(lines) if "MAC2NIX:HOSTS:END" in line)

        # The BEGIN marker's own line carries trailing explanatory comment text
        # ("-- generated by ... do not edit by hand") — only lines strictly
        # between the two sentinel lines are the actual host-block content.
        between_lines = lines[begin_line + 1 : end_line]
        assert all(line.strip() == "" for line in between_lines), "sentinel block must be empty right after init"

    def test_produces_no_host_or_secret_state(self, tmp_path: Path) -> None:
        """init_framework() is host-less — hosts/, users/, .sops.yaml, and secrets/
        are add_host()'s responsibility, not init's."""
        output_dir = tmp_path / "repo"
        init_framework(output_dir)

        assert not (output_dir / "hosts").exists()
        assert not (output_dir / "users").exists()
        assert not (output_dir / ".sops.yaml").exists()
        assert not (output_dir / "secrets").exists()

    def test_creates_missing_parent_directories(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "nested" / "repo"
        init_framework(output_dir)
        assert (output_dir / "flake.nix").is_file()

    def test_raises_on_nonempty_directory(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        output_dir.mkdir()
        (output_dir / "unrelated.txt").write_text("pre-existing content")

        with pytest.raises(ScaffoldError, match="not empty"):
            init_framework(output_dir)

    def test_raises_on_nonempty_directory_writes_nothing(self, tmp_path: Path) -> None:
        output_dir = tmp_path / "repo"
        output_dir.mkdir()
        (output_dir / "unrelated.txt").write_text("pre-existing content")

        before = sorted(p.relative_to(output_dir) for p in output_dir.rglob("*"))

        with pytest.raises(ScaffoldError):
            init_framework(output_dir)

        after = sorted(p.relative_to(output_dir) for p in output_dir.rglob("*"))
        assert before == after


